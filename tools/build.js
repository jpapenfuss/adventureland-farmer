// Builds farmer.js (every role in one file) from src/: common.js, fighter.js, merchant.js, main.js, in that order.
// farmer.js is what loader v1/v2 and the tests run; loader v3 fetches src/ per role (common + its role + main).
//   node tools/build.js          write farmer.js
//   node tools/build.js --check  exit 1 if farmer.js isn't the build of src/ (the tests run this)
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), FILES = ["common.js", "fighter.js", "merchant.js", "main.js"];
const ROLE_FILES = { fighter: ["common.js", "fighter.js", "main.js"], merchant: ["common.js", "merchant.js", "main.js"] };
const read = (f) => fs.readFileSync(path.join(ROOT, "src", f), "utf8").replace(/\n+$/, "\n");
// line 1 of common.js is `const VERSION = "…";` (the loaders and report() read it there); the note goes after it
function build(files = FILES) {
	const parts = files.map(read);
	const [first, ...rest] = parts[0].split("\n");
	return [first, `// GENERATED by tools/build.js from src/${files.join(", src/")} — edit those, then run node tools/build.js`, ...rest].join("\n") + parts.slice(1).join("");
}
module.exports = { build, FILES, ROLE_FILES };
if (require.main === module) {
	const out = build(), target = path.join(ROOT, "farmer.js");
	if (process.argv.includes("--check")) {
		const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
		if (cur !== out) { console.error("FAIL: farmer.js is not the build of src/ — run node tools/build.js"); process.exit(1); }
		console.log("ok - farmer.js is the build of src/");
	} else { fs.writeFileSync(target, out); console.log(`farmer.js written (${out.split("\n").length} lines)`); }
}
