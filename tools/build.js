// Builds farmer.js (every role in one file) from src/, in src/manifest.json's order: shared/*, fighter/*, merchant/,
// main.js. farmer.js is what loaders v1/v2 and the tests run; loader v4 reads the manifest and fetches only its role's
// files (shared + its role + last).
//   node tools/build.js          write farmer.js
//   node tools/build.js --check  exit 1 if farmer.js isn't the build of src/ (test/roles.js runs this)
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), SRC = path.join(ROOT, "src");
const MAN = JSON.parse(fs.readFileSync(path.join(SRC, "manifest.json"), "utf8"));
const FILES = [...MAN.shared, ...MAN.fighter, ...MAN.merchant, ...MAN.last];
const ROLE_FILES = { fighter: [...MAN.shared, ...MAN.fighter, ...MAN.last], merchant: [...MAN.shared, ...MAN.merchant, ...MAN.last] };
const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8").replace(/\n+$/, "\n");
// Role functions (v25.11): a function both roles declare (each in its own files). A role's own file set has just its
// own; the all-in-one build renames them NAME__fighter / NAME__merchant and adds a NAME that calls the one for the
// running character (is_merchant() at the call, so the tests can switch a character's class).
const FN_DECL = (name) => new RegExp(`^((?:async\\s+)?function\\s*)${name}(\\s*\\()`, "gm");
const fn_names = (files) => new Set(files.flatMap((f) => [...read(f).matchAll(/^(?:async\s+)?function\s*([A-Za-z_$][\w$]*)\s*\(/gm)].map((m) => m[1])));
function role_fns() { const m = fn_names(MAN.merchant); return [...fn_names(MAN.fighter)].filter((n) => m.has(n)).sort(); }
// line 1 of the first shared file is `const VERSION = "…";` (the loaders and report() read it there); the note goes after it
function build(files = FILES) {
	const both = files.some((f) => MAN.fighter.includes(f)) && files.some((f) => MAN.merchant.includes(f)) ? role_fns() : [];
	const role = (f) => (MAN.fighter.includes(f) ? "fighter" : MAN.merchant.includes(f) ? "merchant" : null);
	const parts = files.map((f) => { let t = read(f); if (role(f)) for (const n of both) t = t.replace(FN_DECL(n), `$1${n}__${role(f)}$2`); return t; });
	if (both.length) {
		const at = files.findIndex((f) => MAN.last.includes(f)), d = ["// ---- role functions (tools/build.js): the running character's role's own ----",
			...both.map((n) => `function ${n}(...a) { return (is_merchant() ? ${n}__merchant : ${n}__fighter).apply(this, a); }`)].join("\n") + "\n";
		parts.splice(at < 0 ? parts.length : at, 0, d);
	}
	const [first, ...rest] = parts[0].split("\n");
	return [first, `// GENERATED by tools/build.js from src/ (manifest.json: ${files.length} files) — edit those, then run node tools/build.js`, ...rest].join("\n") + parts.slice(1).join("");
}
module.exports = { build, role_fns, FILES, ROLE_FILES, MAN, SRC };
if (require.main === module) {
	const out = build(), target = path.join(ROOT, "farmer.js");
	if (process.argv.includes("--check")) {
		const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
		if (cur !== out) { console.error("FAIL: farmer.js is not the build of src/ — run node tools/build.js"); process.exit(1); }
		console.log("ok - farmer.js is the build of src/");
	} else { fs.writeFileSync(target, out); console.log(`farmer.js written (${out.split("\n").length} lines)`); }
}
